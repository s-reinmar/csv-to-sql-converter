import { ISqlGenerator } from '../contracts/ISqlGenerator';
import { ITableSchema } from '../models/TableSchema';
import { ICsvRow } from '../models/CsvRow';
import { SqlDdlBuilder } from './SqlDdlBuilder';
import { SqlDmlBuilder } from './SqlDmlBuilder';

/**
 * Główny koordynator (Orchestrator) implementujący ISqlGenerator.
 * Łączy nagłówki komentarzy, strukturę tabeli (DDL) oraz wiersze danych (DML)
 * w finalny, kompletny skrypt SQL.
 */
export class SqlGenerator implements ISqlGenerator {
    private readonly ddlBuilder: SqlDdlBuilder;
    private readonly dmlBuilder: SqlDmlBuilder;

    constructor(
        ddlBuilder: SqlDdlBuilder = new SqlDdlBuilder(),
        dmlBuilder: SqlDmlBuilder = new SqlDmlBuilder()
    ) {
        this.ddlBuilder = ddlBuilder;
        this.dmlBuilder = dmlBuilder;
    }

    /**
     * Generuje kompletny skrypt SQL dla podanego schematu tabeli oraz wierszy danych.
     *
     * @param schema Zatwierdzony schemat tabeli
     * @param rows Wiersze sparsowane z pliku CSV
     */
    public generateSql(schema: ITableSchema, rows: ReadonlyArray<ICsvRow>): string {
        const sections: string[] = [];

        // 1. Nagłówek komentarza z metadanymi
        sections.push(this.generateHeaderComment(schema, rows.length));

        // 2. Instrukcja DDL (CREATE TABLE / DROP TABLE)
        const ddl = this.ddlBuilder.generateDdl(schema);
        if (ddl.trim() !== '') {
            sections.push(ddl);
        }

        // 3. Instrukcje DML (INSERT INTO w paczkach)
        if (rows.length > 0) {
            const dml = this.dmlBuilder.generateDml(schema, rows);
            if (dml.trim() !== '') {
                sections.push(dml);
            }
        }

        return sections.join('\n\n') + '\n';
    }

    /**
     * Generuje nagłówek w postaci komentarza SQL z informacjami o konwersji.
     */
    private generateHeaderComment(schema: ITableSchema, rowCount: number): string {
        const timestamp = new Date().toISOString();
        return [
            `-- ==========================================================`,
            `-- Generated by CSV to SQL Converter`,
            `-- Table Name: ${schema.tableName}`,
            `-- Rows Count: ${rowCount}`,
            `-- Generated At: ${timestamp}`,
            `-- ==========================================================`
        ].join('\n');
    }
}